#!/usr/bin/env bash
set -u

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR" || exit 1

SSH_IP="$(awk -F= '/^[[:space:]]*host[[:space:]]*=/{gsub(/[[:space:]]/,"",$2); print $2; exit}' settings.ini)"
DEFAULT_LINE="$(ip -4 route show default | awk '$0 !~ /dev tun0/ {print; exit}')"
DEFAULT_GW="$(awk '{for(i=1;i<=NF;i++) if($i=="via") print $(i+1)}' <<<"$DEFAULT_LINE")"
DEFAULT_DEV="$(awk '{for(i=1;i<=NF;i++) if($i=="dev") print $(i+1)}' <<<"$DEFAULT_LINE")"
DNS_BACKUP="/tmp/resolv.conf.http-ssh-vpn.$$"
DNS_PID=""

cleanup() {
    ip route del 0.0.0.0/1 dev tun0 2>/dev/null || true
    ip route del 128.0.0.0/1 dev tun0 2>/dev/null || true
    if [[ -n "$SSH_IP" && -n "$DEFAULT_GW" && -n "$DEFAULT_DEV" ]]; then
        ip route del "$SSH_IP/32" via "$DEFAULT_GW" dev "$DEFAULT_DEV" 2>/dev/null || true
    fi
    [[ -n "$DNS_PID" ]] && kill "$DNS_PID" 2>/dev/null || true
    [[ -f "$DNS_BACKUP" ]] && cp "$DNS_BACKUP" /etc/resolv.conf 2>/dev/null || true
    rm -f "$DNS_BACKUP"
    ip link set tun0 down 2>/dev/null || true
    ip tuntap del dev tun0 mode tun 2>/dev/null || true
}
trap cleanup EXIT INT TERM

[[ $EUID -eq 0 ]] || { echo "Run as root."; exit 1; }
[[ -n "$SSH_IP" && -n "$DEFAULT_GW" && -n "$DEFAULT_DEV" ]] || {
    echo "Could not determine the SSH host or original default route."
    exit 1
}
ss -ltn 2>/dev/null | grep -q ':1080' || {
    echo "SOCKS port 1080 is not listening; refusing to change routes."
    exit 1
}
for cmd in badvpn-tun2socks dns2socks; do
    command -v "$cmd" >/dev/null 2>&1 || { echo "Missing command: $cmd"; exit 1; }
done

# Remove only leftovers owned by this setup; do not flush all iptables rules.
ip link set tun0 down 2>/dev/null || true
ip tuntap del dev tun0 mode tun 2>/dev/null || true

ip tuntap add dev tun0 mode tun
ip addr add 10.0.0.1/24 dev tun0
ip link set dev tun0 up

# Keep the SSH transport outside tun0 to prevent a routing loop.
ip route replace "$SSH_IP/32" via "$DEFAULT_GW" dev "$DEFAULT_DEV"
# More-specific split routes preserve the original Wi-Fi default route.
ip route replace 0.0.0.0/1 via 10.0.0.2 dev tun0
ip route replace 128.0.0.0/1 via 10.0.0.2 dev tun0

cp /etc/resolv.conf "$DNS_BACKUP"
dns2socks 127.0.0.1:1080 1.1.1.1:53 127.0.0.1:53 >/dev/null 2>&1 &
DNS_PID=$!
sleep 1
# resolv.conf accepts an IP address, not IP:port.
printf '# Generated by dns2socks\nnameserver 127.0.0.1\n' > /etc/resolv.conf

badvpn-tun2socks \
    --tundev tun0 \
    --netif-ipaddr 10.0.0.2 \
    --netif-netmask 255.255.255.0 \
    --socks-server-addr 127.0.0.1:1080 \
    --udpgw-remote-server-addr 127.0.0.1:7300
